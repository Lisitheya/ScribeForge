export function genHeadline(genreId?: string): string {
  const g = GENRES.find(x => x.id === genreId);
  if (!g) return comboHeadline();
  return maybe(.55) ? pick(g.heads) : comboHeadline();
}

export function genPlot(genreId?: string): string {
  const g = GENRES.find(x => x.id === genreId) ?? GENRES[0];
  return pick(g.plots);
}

