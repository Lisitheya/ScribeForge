const byId = (id: string) => CULTURES.find(c => c.id === id) ?? CULTURES[0];
export const ERAS: EraName[] = ['Античность', 'Средневековье', 'Новое время', 'Азия', 'Фэнтези', 'Будущее'];

function genSyll(cultureId: string, gender: Gender, len: 'short' | 'mid' | 'long', first: string): string {
  const c = byId(cultureId);
  const syl = len === 'short' ? 2 : len === 'mid' ? 2 + rnd(2) : 3 + rnd(2);
  let s = pick(c.start);
  for (let i = 0; i < syl - 2 && c.mid.length; i++) s += pick(c.mid);
  const ends = gender === 'female' ? c.endF : gender === 'male' ? c.endM : c.endM.concat(c.endF);
  if (ends.length) s += pick(ends);
  s = cap(s.replace(/[^A-Za-zА-Яа-яЁё\-'_0-9]/g, ''));
  if (first && !s.toLowerCase().startsWith(first.toLowerCase())) {
    for (let t = 0; t < 30 && !s.toLowerCase().startsWith(first.toLowerCase()); t++) s = genSyll(cultureId, gender, len, '');
    if (!s.toLowerCase().startsWith(first.toLowerCase())) s = cap(first) + s.slice(1);
  }
  return s;
}

function genGiven(cultureId: string, gender: Gender, len: 'short' | 'mid' | 'long', first: string): string {
  if (cultureId === 'roman') return gender === 'female'
    ? pick(['Аврелия','Ливия','Октавия','Сервилия','Юния','Тертулла'])
    : pick(['Гай','Луций','Марк','Публий','Квинт','Тит','Авл','Гней','Сервий']);
  if (cultureId === 'korean') return genSyll(cultureId, gender, 'short', '') + (maybe(.5) ? pick(['джун','сок','хун','ин','а']) : '');
  return genSyll(cultureId, gender, len, first);
}

export function genName(cultureId: string, gender: Gender, len: 'short'|'mid'|'long', first: string): string {
  return genGiven(cultureId, gender, len, first);
}

export function fullNameFor(cultureId: string, gender: Gender): string {
  const c = byId(cultureId);
  const g = gender === 'neutral' ? (maybe() ? 'male' : 'female') : gender;
  return c.full(genGiven(cultureId, g, 'mid', ''), g);
}

