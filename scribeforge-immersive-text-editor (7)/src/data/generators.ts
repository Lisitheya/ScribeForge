const rnd = (n: number) => {
  const a = new Uint32Array(1);
  crypto.getRandomValues(a);
  return a[0] % n;
};
export const pick = <T,>(arr: T[]): T => arr[rnd(arr.length)];
const maybe = (p = 0.5) => rnd(100) < p * 100;
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
// уникализация серии результатов
export function uniqueSeries(gen: () => string, count: number): string[] {
  const out = new Set<string>();
  for (let i = 0; i < count * 14 && out.size < count; i++) out.add(gen());
  return [...out];
}

